// Generates lib/ui/keyline/keyline_icons.g.dart from a local copy of the
// Keyline Icons React package (https://keylineicons.com, MIT license).
//
// Usage:
//   dart run tool/gen_keyline_icons.dart [path/to/@keyline-icons/react/dist/index.js]
//
// `index.js` holds the rounded stroke style (1,366 icons). The other styles
// ship as fill.js, two-tone.js, duotone.js and sharp*.js in the same folder;
// pass one of those to generate that style instead (adjust the output path
// with a second argument if you want to keep both).
import 'dart:io';

const _defaultInput =
    'D:/ClaudeLocalExperiments/encode-this/node_modules/@keyline-icons/react/'
    'dist/index.js';
const _defaultOutput = 'lib/ui/keyline/keyline_icons.g.dart';

/// Dart keywords an icon name must not collide with.
const _reserved = {
  'assert',
  'break',
  'case',
  'catch',
  'class',
  'const',
  'continue',
  'default',
  'do',
  'else',
  'enum',
  'extends',
  'false',
  'final',
  'finally',
  'for',
  'if',
  'in',
  'is',
  'new',
  'null',
  'rethrow',
  'return',
  'super',
  'switch',
  'this',
  'throw',
  'true',
  'try',
  'var',
  'void',
  'while',
  'with',
};

String _dartName(String pascal) {
  final lower = pascal[0].toLowerCase() + pascal.substring(1);
  return _reserved.contains(lower) ? '${lower}Icon' : lower;
}

Map<String, String> _attrs(String source) => {
  for (final m in RegExp(r'(\w+): "([^"]*)"').allMatches(source))
    m.group(1)!: m.group(2)!,
};

void main(List<String> args) {
  final input = args.isNotEmpty ? args[0] : _defaultInput;
  final output = args.length > 1 ? args[1] : _defaultOutput;
  final js = File(input).readAsStringSync();

  final icon = RegExp(
    r'export function (\w+)\(props\) \{\s*return \(([\s\S]*?)\);\s*\}\n',
  );
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_keyline_icons.dart. Do not edit.')
    ..writeln('//')
    ..writeln('// Keyline Icons (https://keylineicons.com), MIT license.')
    ..writeln('// See third_party/KEYLINE_ICONS_LICENSE.md.')
    ..writeln('// dart format off')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln("import 'keyline_icon_data.dart';")
    ..writeln()
    ..writeln('/// Every icon in the set, on a 24x24 grid.')
    ..writeln('abstract final class KeylineIcons {');

  var count = 0;
  final seen = <String>{};
  final names = <String>[];
  for (final m in icon.allMatches(js)) {
    final name = m.group(1)!;
    final body = m.group(2)!;
    final dartName = _dartName(name);
    if (!seen.add(dartName)) {
      stderr.writeln('skipping duplicate name $dartName');
      continue;
    }

    // Root attributes apply to every path unless the path overrides them.
    final root = RegExp(r'_jsxs?\(Icon, \{([^}]*?), \.\.\.props')
        .firstMatch(body);
    final rootAttrs = root == null
        ? <String, String>{}
        : _attrs(root.group(1)!);
    final rootFill = rootAttrs['fill'] ?? 'none';
    final rootStroke = rootAttrs['stroke'] ?? 'none';

    final paths = <String>[];
    for (final p in RegExp(r'_jsxs?\("path", \{(.*?)\}\)').allMatches(body)) {
      final a = _attrs(p.group(1)!);
      final d = a['d'];
      if (d == null) continue;
      final fill = (a['fill'] ?? rootFill) != 'none';
      final stroke = (a['stroke'] ?? rootStroke) != 'none';
      final evenOdd = a['fillRule'] == 'evenodd';
      final extra = [
        if (fill) 'fill: true',
        if (!stroke) 'stroke: false',
        if (evenOdd) 'evenOdd: true',
      ].join(', ');
      paths.add("KeylinePath('$d'${extra.isEmpty ? '' : ', $extra'})");
    }
    if (paths.isEmpty) continue;
    out.writeln(
      "  static const $dartName = KeylineIconData('$name', [${paths.join(', ')}]);",
    );
    names.add(dartName);
    count++;
  }
  // Handy for tests and icon pickers. Not referenced by the app itself, so a
  // release build drops it.
  out.writeln('  static const all = <KeylineIconData>[');
  for (final n in names) {
    out.writeln('    $n,');
  }
  out.writeln('  ];');
  out.writeln('}');

  File(output)
    ..createSync(recursive: true)
    ..writeAsStringSync(out.toString());
  stdout.writeln('Wrote $count icons to $output');
}
